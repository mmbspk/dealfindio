"""
Price prediction model for ML-powered price forecasting.

Stores predicted future prices for products using machine learning models.
Predictions are scoped by product, chain, and target week.
"""

from datetime import datetime
from uuid import UUID

from sqlalchemy import ForeignKey, Index, String, UniqueConstraint
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .base import Base


class PricePrediction(Base):
    """
    Machine learning predicted price for a product.

    Stores price predictions generated by ML models for future weeks.
    Includes confidence intervals and prediction metadata.

    Predictions are identified uniquely by (product_id, chain, prediction_week).
    A NULL chain represents an aggregated prediction across all chains.

    Attributes:
        product_id: Foreign key to Product
        chain: Chain name ('coles', 'woolworths', etc.) or NULL for aggregate
        predicted_price_cents: Predicted price in AUD cents
        prediction_week: Monday date of the predicted week
        confidence_interval_low: Lower bound of confidence interval (cents)
        confidence_interval_high: Upper bound of confidence interval (cents)
        is_likely_sale: Whether prediction suggests item will be on sale
        model_version: Version of ML model used for prediction
        generated_at: Timestamp when prediction was generated
        product: Relationship to Product
    """

    __tablename__ = "price_predictions"

    product_id: Mapped[UUID] = mapped_column(ForeignKey("products.id"))
    chain: Mapped[str | None] = mapped_column(String(50))
    predicted_price_cents: Mapped[int] = mapped_column(nullable=False)
    prediction_week: Mapped[datetime] = mapped_column(nullable=False)
    confidence_interval_low: Mapped[int | None]
    confidence_interval_high: Mapped[int | None]
    is_likely_sale: Mapped[bool] = mapped_column(default=False)
    model_version: Mapped[str | None] = mapped_column(String(50))

    # Relationships
    product: Mapped["Product"] = relationship(
        back_populates="predictions",
        foreign_keys=[product_id],
    )

    __table_args__ = (
        UniqueConstraint("product_id", "chain", "prediction_week", name="unique_prediction"),
        Index("idx_predictions_product", "product_id", "prediction_week"),
    )

    def __repr__(self) -> str:
        return f"<PricePrediction product_id={self.product_id} chain={self.chain} week={self.prediction_week} id={self.id}>"
